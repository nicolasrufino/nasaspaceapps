"""Build explicitly untrained ONNX wiring fixtures for CONTRACTS section 2.

Run once: python -m ml.export_placeholders
Use --out ml/runs/placeholders to reproduce without replacing published models.
"""
import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import onnx
from onnx import TensorProto, helper, numpy_helper

from ml.check_exports import EXPORTS, SPECS, check


def make_model(name):
    inputs, outputs = SPECS[name]
    input_name, input_shape = next(iter(inputs.items()))
    output_name, output_shape = next(iter(outputs.items()))
    nodes = []
    features = input_name
    feature_count = input_shape[1]
    if name == "terrain_cls":
        nodes += [helper.make_node("GlobalAveragePool", [input_name], ["pooled"]),
                  helper.make_node("Flatten", ["pooled"], ["features"], axis=1)]
        features = "features"
    width = output_shape[1]
    weights = numpy_helper.from_array(np.zeros((feature_count, width), np.float32), "weights")
    bias = np.zeros((1, width), np.float32)
    bias[0, 0] = 1  # unknown terrain / stay; not a learned or safe-navigation decision.
    nodes += [helper.make_node("MatMul", [features, "weights"], ["zeros"]),
              helper.make_node("Add", ["zeros", "bias"], [output_name])]
    graph = helper.make_graph(
        nodes, f"{name}_UNTRAINED_PLACEHOLDER",
        [helper.make_tensor_value_info(input_name, TensorProto.FLOAT, input_shape)],
        [helper.make_tensor_value_info(output_name, TensorProto.FLOAT, output_shape)],
        [weights, numpy_helper.from_array(bias, "bias")],
    )
    model = helper.make_model(graph, producer_name="Martian Map placeholder generator",
                              opset_imports=[helper.make_opsetid("", 17)])
    model.ir_version = 8
    model.doc_string = "UNTRAINED placeholder for interface wiring only. Do not use as predictions."
    helper.set_model_props(model, {"placeholder": "true", "contract": "CONTRACTS.md section 2"})
    onnx.checker.check_model(model)
    return model.SerializeToString()


def export(destination):
    destination = Path(destination)
    targets = [destination / f"{name}.{ext}" for name in SPECS for ext in ("onnx", "json")]
    if any(p.exists() for p in targets):
        raise FileExistsError("Refusing to overwrite exports; use a fresh --out directory.")
    destination.mkdir(parents=True, exist_ok=True)
    for name in SPECS:
        data = make_model(name)
        (destination / f"{name}.onnx").write_bytes(data)
        metadata = {
            "placeholder": True,
            "data_source": "No training data; deterministic interface fixture generated by ml/export_placeholders.py",
            "behavior": "Constant logits: index 0 = 1, other indices = 0 (unknown terrain / stay)",
            "limitations": "Not trained, not evaluated, not a navigation policy or terrain prediction.",
            "sha256": hashlib.sha256(data).hexdigest(),
            "opset": 17, "ir_version": 8,
            "reproduce": "python -m ml.export_placeholders --out ml/runs/placeholders",
        }
        (destination / f"{name}.json").write_text(
            json.dumps(metadata, indent=2) + "\n", encoding="utf-8", newline="\n",
        )
    names, errors = check(destination)
    if errors:
        raise RuntimeError("; ".join(errors))
    return names


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=EXPORTS)
    args = parser.parse_args()
    print("Exported and ran untrained placeholders:", export(args.out))
