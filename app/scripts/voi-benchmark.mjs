import { readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import { resolve, dirname } from 'node:path'
import { loadInputs } from '../../ml/pitch_metrics/run.mjs'
import { createScout, launchScoutFlight, completeScoutFlight } from '../src/scout.js'
import { chooseVoi, createVoiContext, VOI_DEFAULTS } from '../src/scout-voi.js'
import { generatedWorld } from './voi-worlds.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
function simulate(world, targets, strategy) {
  const state = createScout(world, targets), decisions = [], context = strategy === 'voi' ? createVoiContext(world) : null
  while (state.flights.length < state.maxFlights) {
    let choice
    if (context) {
      choice = chooseVoi(world, state, context)
      decisions.push({ selected: !!choice.flight, reason: choice.reason, candidates: choice.candidate_strips,
        expected_gain_j: choice.flight?.expected_gain_j ?? 0, best_gain_j: choice.best_gain_j ?? 0,
        sample_se_j: choice.flight?.sample_se_j ?? null, compute_ms: choice.compute_ms,
        failed_samples_before: choice.failed_samples_before ?? 0, failed_samples_after: choice.flight?.failed_samples_after ?? null })
    }
    const f = context ? launchScoutFlight(world, state, () => choice.flight) : launchScoutFlight(world, state)
    if (!f) break
    if (f.metres > 1000 + 1e-6 || f.metres <= 0) throw new Error('Invalid flight budget')
    completeScoutFlight(world, state)
  }
  const at = ([x, y]) => y * world.meta.width + x
  return { flights: state.flights.length, flight_metres: state.flights.reduce((a, f) => a + f.metres, 0),
    stops: state.route.stops, route_energy_j: state.route.energy_j,
    hidden_hazard_cells_on_route: new Set(state.route.cells.map(at).filter((i) => world.layers.rocks_fine[i])).size,
    fully_scanned: state.route.cells.every((c) => state.scanned[at(c)]), decisions }
}

const cases = [{ name: 'Gale', ...loadInputs() }, ...Array.from({ length: 10 }, (_, k) => ({ name: `Generated ${k + 1}`, ...generatedWorld(k + 1) }))]
const comparisons = cases.map(({ name, world, targets }) => {
  const baseline = simulate(world, targets, 'f4'), voi = simulate(world, targets, 'voi')
  const sameStops = baseline.stops.length === voi.stops.length && baseline.stops.every((id) => voi.stops.includes(id))
  const passes = sameStops && voi.hidden_hazard_cells_on_route <= baseline.hidden_hazard_cells_on_route
    && (!baseline.fully_scanned || voi.fully_scanned) && voi.route_energy_j <= baseline.route_energy_j + 1
    && voi.flight_metres <= baseline.flight_metres + 1e-6
  console.log(`${name}: F4 ${baseline.flights} flights/${baseline.hidden_hazard_cells_on_route} hazard cells; VOI ${voi.flights}/${voi.hidden_hazard_cells_on_route}; promotion ${passes ? 'pass' : 'fail'}`)
  return { name, baseline, voi, passes }
})
const files = ['app/src/scout-voi.js','app/src/scout.js','app/src/plan.js','app/src/walk.js','app/src/belief.js',
  'app/src/belief-weights.js','app/scripts/voi-worlds.mjs','app/scripts/voi-benchmark.mjs']
const report = { config: VOI_DEFAULTS, promotion_passed: comparisons.every((r) => r.passes),
  gate: 'Every case: same stops, no more stored hazard crossings, retain full coverage if baseline has it, no greater walking energy (1 J tolerance) or flight distance.',
  source_sha256: Object.fromEntries(files.map((f) => [f, createHash('sha256').update(readFileSync(resolve(root, f), 'utf8').replace(/\r\n/g, '\n')).digest('hex')])),
  limitations: ['Simulation, not field validation.', 'Uncalibrated belief model and assumed 2x2-cell correlation.',
    'Counterfactual walking keeps the current stop order; failed runs cost 4x initial budget and are never dropped.',
    'Transit, recharge, daylight and helicopter energy are excluded in BOTH strategies.',
    'Timings are local-machine measurements; seeded route/value outputs are deterministic.'], comparisons }
writeFileSync(resolve(root, 'app/scripts/voi-benchmark.json'), JSON.stringify(report, null, 2) + '\n')
const kJ = (n) => (n / 1000).toFixed(1)
const rows = comparisons.map(({ name, baseline: b, voi: v, passes }) =>
  `| ${name} | ${b.flights} / ${v.flights} | ${b.flight_metres.toFixed(0)} / ${v.flight_metres.toFixed(0)} | ${b.stops.length} / ${v.stops.length} | ${b.hidden_hazard_cells_on_route} / ${v.hidden_hazard_cells_on_route} | ${kJ(b.route_energy_j)} / ${kJ(v.route_energy_j)} | ${b.fully_scanned} / ${v.fully_scanned} | ${passes ? 'pass' : 'fail'} |`)
writeFileSync(resolve(root, 'app/scripts/VOI_RESULTS.md'), `# A6 comparison\n\nGenerated by \`node app/scripts/voi-benchmark.mjs\`. Each paired column is **F4 / VOI**. This is a simulation comparison, not a real-Mars score.\n\n| World | Flights | Flight m | Stops | Stored hazard cells crossed | Walking kJ | Fully scanned | Promotion |\n|---|---:|---:|---:|---:|---:|---|---|\n${rows.join('\n')}\n\nPromotion gate: **${report.promotion_passed ? 'passed' : 'failed'}**. See [VOI.md](VOI.md) for assumptions and [voi-benchmark.json](voi-benchmark.json) for per-decision gains, failed samples, timings and source hashes.\n`)
